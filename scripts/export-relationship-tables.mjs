/**
 * Exports the ArchiMate relationship tables inherited from archimate-js
 * (lib/metamodel/*RelationshipMap.js) as a single readable JSON file.
 *
 * These tables are NOT used by the component at runtime (allowed
 * relationships are provided by the host); they are published as raw
 * material for the Ossie-studio catalogue (see ticket "Les types
 * ArchiMate 3.2 en version de base, et les règles de relation").
 *
 * Usage: node scripts/export-relationship-tables.mjs
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { FULL_ELEMENT_MAP } from '../lib/util/ModelUtil.js';

const LETTER_TO_RELATIONSHIP = {
  s: 'Specialization',
  c: 'Composition',
  g: 'Aggregation',
  i: 'Assignment',
  r: 'Realization',
  v: 'Serving',
  a: 'Access',
  n: 'Influence',
  t: 'Triggering',
  f: 'Flow',
  o: 'Association'
};

const tables = {};

for (const [ sourceType, descriptor ] of FULL_ELEMENT_MAP) {
  const relationshipMap = descriptor.relationshipMap;

  if (!relationshipMap) {
    continue;
  }

  const targets = {};

  for (const [ targetType, letters ] of relationshipMap) {
    targets[ targetType ] = [ ...letters ].map((letter) => {
      const relationship = LETTER_TO_RELATIONSHIP[ letter ];

      if (!relationship) {
        throw new Error(
          `unknown relationship letter '${ letter }' for ${ sourceType } -> ${ targetType }`);
    }

      return relationship;
    });
  }

  tables[ sourceType ] = targets;
}

const output = {
  $comment:
    'Allowed ArchiMate 3.x relationships per (source, target) pair, ' +
    'extracted from archimate-js (MIT, Vincent Boulet). ' +
    'Generated by scripts/export-relationship-tables.mjs - do not edit by hand.',
  relationships: Object.values(LETTER_TO_RELATIONSHIP),
  allowed: tables
};

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'data');
mkdirSync(outDir, { recursive: true });

const outFile = join(outDir, 'archimate-relationship-tables.json');
writeFileSync(outFile, JSON.stringify(output, null, 2) + '\n');

console.log(
  `wrote ${ outFile }: ${ Object.keys(tables).length } source types`);
